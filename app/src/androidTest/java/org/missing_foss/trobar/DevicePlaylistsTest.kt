// Playlists a person made in the sync folder, as collectDevicePlaylists
// finds them: walkDevicePlaylists with the listing and the file reads
// injected (as FolderScanTest does), and parseDevicePlaylist on raw bytes.
package org.missing_foss.trobar

import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class DevicePlaylistsTest {
    private val marker = "# Generated by Trobar"

    private class Tree {
        val children = HashMap<String, List<ChildEntry>>()
        val files = HashMap<String, ByteArray>()
        val listed = mutableListOf<String>()
        fun dir(parent: String, id: String, name: String) = add(parent, ChildEntry(id, name, true, 0))
        fun file(parent: String, id: String, name: String, text: String) = file(parent, id, name, text.toByteArray())
        fun file(parent: String, id: String, name: String, bytes: ByteArray) {
            files[id] = bytes
            add(parent, ChildEntry(id, name, false, bytes.size.toLong()))
        }
        private fun add(parent: String, e: ChildEntry) { children[parent] = (children[parent] ?: emptyList()) + e }
        fun walk() = walkDevicePlaylists("root", { listed.add(it); children[it] ?: emptyList() }) { files[it] }
    }

    @Test
    fun collectsPlaylistsAnywhereButTrobarsOwnAndTheConfigFolder() {
        val t = Tree()
        t.file("root", "f1", "Road Trip.m3u8", "#EXTM3U\n#EXTINF:20,A - T\nA/B/01 - T.flac\n\n")
        t.dir("root", "d1", "Playlists")
        t.file("d1", "f2", "Gym.m3u", "A/B/02 - U.mp3\r\n../A/B/03 - V.mp3\r\n")
        t.file("root", "f3", "Mix.m3u8", "#EXTM3U\n$marker\n#PLAYLIST:Mix\nA/B/x.mp3\n")
        t.dir("root", "d2", ".trobar")
        t.file("d2", "f4", "cache.m3u", "A/B/x.mp3\n")
        t.file("root", "f5", "Later.m3u", "#EXTM3U\n#PLAYLIST:x\n$marker\nA/B/y.mp3\n")
        t.file("root", "f6", "notes.txt", "A/B/z.mp3\n")
        assertEquals(
            listOf(
                DevicePlaylist("Later.m3u", listOf("A/B/y.mp3")),  // the marker counts on line 2 only
                DevicePlaylist("Playlists/Gym.m3u", listOf("A/B/02 - U.mp3", "../A/B/03 - V.mp3")),
                DevicePlaylist("Road Trip.m3u8", listOf("A/B/01 - T.flac")),
            ),
            t.walk(),
        )
        assertEquals(listOf("root", "d1"), t.listed)  // .trobar/ is never listed
    }

    @Test
    fun aBomIsDroppedAndLatin1IsReadAsLatin1() {
        assertEquals(listOf("A/B/01 - T.flac"), parseDevicePlaylist("\uFEFFA/B/01 - T.flac\n".toByteArray()))
        assertNull(parseDevicePlaylist("\uFEFF#EXTM3U\n$marker\nA/B/x.mp3\n".toByteArray()))
        val latin1 = "Björk/Homogenic/01 - Hunter.mp3\n".toByteArray(Charsets.ISO_8859_1)
        assertEquals(listOf("Björk/Homogenic/01 - Hunter.mp3"), parseDevicePlaylist(latin1))
    }

    // All or nothing: the server removes any playlist missing from an
    // upload, so anything unreadable means no upload at all.
    @Test
    fun anUnreadableFileMeansNothingIsSent() {
        val t = Tree()
        t.file("root", "f1", "A.m3u", "x/y/z.mp3\n")
        t.children["root"] = t.children["root"]!! + ChildEntry("gone", "B.m3u", false, 0)
        assertNull(t.walk())
    }

    @Test
    fun aFailedRootListingMeansNothingIsSent() {
        // Not an empty set: that would remove every playlist made on the device.
        assertNull(walkDevicePlaylists("root", { null }) { null })
    }

    @Test
    fun aFailedFolderListingMeansNothingIsSent() {
        val t = Tree()
        t.file("root", "f1", "A.m3u", "x/y/z.mp3\n")
        t.dir("root", "d1", "Playlists")  // listed as a folder, but its listing fails
        assertNull(walkDevicePlaylists("root", { if (it == "d1") null else t.children[it] ?: emptyList() }) { t.files[it] })
    }

    @Test
    fun dotFilesAndHiddenFoldersAreLeftOut() {
        val t = Tree()
        t.dir("root", "d1", "Playlists")
        t.file("d1", "f1", "Gym.m3u", "A/B/01 - T.flac\n")
        // macOS's AppleDouble companion: binary, then junk lines.
        t.file("d1", "f2", "._Gym.m3u", byteArrayOf(0, 5, 22, 7) + "Mac OS X\nA/B/x\nC/D/y\n".toByteArray())
        t.dir("root", "d2", ".Trashes")
        t.file("d2", "f3", "Old.m3u", "A/B/z.flac\n")
        assertEquals(listOf(DevicePlaylist("Playlists/Gym.m3u", listOf("A/B/01 - T.flac"))), t.walk())
        assertEquals(listOf("root", "d1"), t.listed)  // the hidden folder is never listed
    }
}
