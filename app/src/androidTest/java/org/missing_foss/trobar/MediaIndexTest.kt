// What a sync wrote or removed reaches the media index, as filesystem
// paths under the picked folder, unless .nomedia hides the folder from
// media apps; and the sync reports exactly those files.

package org.missing_foss.trobar

import android.net.Uri
import android.os.Environment
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import kotlinx.coroutines.runBlocking
import okhttp3.mockwebserver.Dispatcher
import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import okhttp3.mockwebserver.RecordedRequest
import okio.Buffer
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File

@RunWith(AndroidJUnit4::class)
class MediaIndexTest {
    private val context = InstrumentationRegistry.getInstrumentation().targetContext
    private val defaultScan = MediaIndex.scanPaths
    private val scanned = mutableListOf<List<String>>()
    private lateinit var tempDir: File
    private lateinit var server: MockWebServer
    private var changesJson = ""

    @Before
    fun setUp() {
        MediaIndex.scanPaths = { _, paths -> scanned += paths.toList() }
        tempDir = File(context.cacheDir, "media_index_${System.nanoTime()}").apply { mkdirs() }
        server = MockWebServer().apply {
            dispatcher = object : Dispatcher() {
                override fun dispatch(request: RecordedRequest): MockResponse {
                    val path = request.path ?: ""
                    return when {
                        path.startsWith("/api/device/changes") -> MockResponse().setBody(changesJson)
                        path.startsWith("/api/device/file/") -> MockResponse().setBody(Buffer().write(ByteArray(10) { 1 }))
                        else -> MockResponse().setBody("{}")
                    }
                }
            }
            start()
        }
    }

    @After
    fun tearDown() {
        MediaIndex.scanPaths = defaultScan
        server.shutdown()
        tempDir.deleteRecursively()
    }

    private fun tree(docId: String): Uri =
        Uri.parse("content://com.android.externalstorage.documents/tree/" + Uri.encode(docId))

    @Test
    @Suppress("DEPRECATION")
    fun aFolderOnPrimaryStorageIsUnderItsPath() {
        assertEquals(File(Environment.getExternalStorageDirectory(), "Music/Trobar"),
            MediaIndex.directoryOf(context, tree("primary:Music/Trobar")))
        assertEquals(Environment.getExternalStorageDirectory(), MediaIndex.directoryOf(context, tree("primary:")))
    }

    @Test
    fun aFolderOnACardIsUnderTheCardsMount() {
        // No such card here, so the fallback under /storage is what answers.
        assertEquals(File("/storage/1234-ABCD/Music"), MediaIndex.directoryOf(context, tree("1234-ABCD:Music")))
    }

    @Test
    fun aFolderFromAnotherProviderHasNoPath() {
        assertNull(MediaIndex.directoryOf(context,
            Uri.parse("content://com.example.cloud.documents/tree/" + Uri.encode("root:Music"))))
    }

    @Test
    fun theChangedFilesAreScannedUnderTheFolderOnceEachAndInBatches() {
        val names = (1..450).map { "A/B/$it.flac" }
        assertEquals(450, MediaIndex.afterSync(context, Uri.fromFile(tempDir), names + names.take(3), false))
        assertEquals(listOf(200, 200, 50), scanned.map { it.size })
        assertEquals(File(tempDir, "A/B/1.flac").path, scanned[0][0])
    }

    @Test
    fun nothingIsScannedWhenNomediaHidesTheFolder() {
        assertEquals(0, MediaIndex.afterSync(context, Uri.fromFile(tempDir), listOf("A/B/1.flac"), true))
        assertEquals(0, scanned.size)
    }

    @Test
    fun aSyncReportsTheFilesItWroteAndRemoved() {
        File(tempDir, "Old").mkdirs()
        File(tempDir, "Old/Gone.flac").writeBytes(ByteArray(4))
        // A playlist the server no longer sends, marked as Trobar's: removed.
        File(tempDir, "Stale.m3u8").writeText("# Generated by Trobar\nA/B/01 - T.flac\n")
        changesJson = """{"to_download": [{"track_id": 1, "relative_path": "A/B/01 - T.flac", "size": 10}],
            "to_delete": [{"track_id": 9, "relative_path": "Old/Gone.flac"}], "downloaded": [],
            "playlists": [{"name": "Mix", "filename": "Mix.m3u8", "content": "# Generated by Trobar\nA/B/01 - T.flac\n"}]}"""
        val result = runBlocking {
            SyncEngine.runIn(context, ApiClient(context, server.url("/").toString().trimEnd('/'), "t0k"), Uri.fromFile(tempDir))
        }
        assertEquals(listOf("A/B/01 - T.flac", "Mix.m3u8", "Old/Gone.flac", "Stale.m3u8"), result.changedPaths.sorted())
    }
}
