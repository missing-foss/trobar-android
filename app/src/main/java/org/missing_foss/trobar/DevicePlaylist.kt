package org.missing_foss.trobar

import android.content.Context
import android.net.Uri
import android.provider.DocumentsContract
import java.nio.ByteBuffer
import java.nio.charset.CharacterCodingException
import java.nio.charset.CodingErrorAction

/** A playlist a person made in the sync folder: its path from the folder
 * root and its entries (the non-comment lines), in order, as written. The
 * server resolves the entries; see its POST /api/device/playlists. */
data class DevicePlaylist(val path: String, val entries: List<String>)

private const val TROBAR_MARKER = "# Generated by Trobar"
private val PLAYLIST_EXTENSIONS = setOf("m3u", "m3u8")

/** The entries of one playlist file, or null when Trobar wrote it: its
 * second line is the marker, the same line the server's .m3u reader and the
 * desktop app check. A file that isn't valid UTF-8 is read as Latin-1, the
 * usual encoding of an older .m3u. trim() drops a BOM along with the
 * whitespace. */
internal fun parseDevicePlaylist(bytes: ByteArray): List<String>? {
    val text = try {
        Charsets.UTF_8.newDecoder()
            .onMalformedInput(CodingErrorAction.REPORT)
            .onUnmappableCharacter(CodingErrorAction.REPORT)
            .decode(ByteBuffer.wrap(bytes)).toString()
    } catch (ignored: CharacterCodingException) {
        String(bytes, Charsets.ISO_8859_1)
    }
    val lines = text.lines()
    if (lines.size > 1 && lines[1].trim() == TROBAR_MARKER) return null
    return lines.map { it.trim().removePrefix("\uFEFF").trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") }
}

/** Every playlist a person made in the folder: .m3u and .m3u8 files,
 * except Trobar's own, and except anything under a name starting with a dot:
 * `.trobar/`, hidden folders, and the `._` files macOS writes beside every
 * file on a FAT or exFAT card. The listing and the file read are injected,
 * as for walkForeignAudio, so the walk can be tested without a
 * DocumentsProvider; one listing query per directory. Sorted by path.
 *
 * All or nothing: null when any listing or read fails. The server removes
 * any playlist missing from an upload, so a partial set would delete those
 * playlists with their settings and mirrors. */
internal fun walkDevicePlaylists(
    rootId: String,
    listChildren: (String) -> List<ChildEntry>?,
    read: (String) -> ByteArray?,
): List<DevicePlaylist>? {
    val found = mutableListOf<DevicePlaylist>()
    val pending = ArrayDeque<Pair<String, String>>()
    pending.add(rootId to "")
    val seen = HashSet<String>()
    while (pending.isNotEmpty()) {
        val (documentId, prefix) = pending.removeFirst()
        if (!seen.add(documentId)) continue
        val children = listChildren(documentId) ?: return null
        for (child in children) {
            if (child.name.startsWith(".")) continue
            val path = if (prefix.isEmpty()) child.name else "$prefix/${child.name}"
            if (child.isDirectory) {
                pending.add(child.documentId to path)
            } else if (child.name.substringAfterLast('.', "").lowercase() in PLAYLIST_EXTENSIONS) {
                val bytes = read(child.documentId) ?: return null
                parseDevicePlaylist(bytes)?.let { found.add(DevicePlaylist(path, it)) }
            }
        }
    }
    return found.sortedBy { it.path }
}

/** [walkDevicePlaylists] over the picked SAF tree; null if any of it can't
 * be read. */
fun collectDevicePlaylists(context: Context, treeUri: Uri): List<DevicePlaylist>? {
    val rootId = try {
        DocumentsContract.getTreeDocumentId(treeUri)
    } catch (ignored: IllegalArgumentException) {
        return null
    }
    return walkDevicePlaylists(rootId, { readChildren(context, treeUri, it) }) { documentId ->
        try {
            context.contentResolver.openInputStream(
                DocumentsContract.buildDocumentUriUsingTree(treeUri, documentId))?.use { it.readBytes() }
        } catch (ignored: Exception) {
            null
        }
    }
}
