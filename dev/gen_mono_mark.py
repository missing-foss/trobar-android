"""Draws the single-colour mark from brand/BRAND.md §1 (200 grid, centre
100,100) as exact circles and arcs, one even-odd path:

- brand/trobar-mark-mono.svg: the canonical copy, for the other clients;
- app/src/main/res/drawable/ic_trobar_mark_mono.xml;
- app/src/main/res/drawable/ic_notification.xml: the small variant's geometry
  (§1: no pommels, a 96 star with corner radius 16, hub r34, dot r16), since
  a status-bar icon is under 24 dp;
- app/src/main/res/drawable/ic_launcher_monochrome.xml: the same path inside
  the adaptive icon's safe zone;
- docs/icon-pack/arcticons.svg: the same shapes as 1 px white lines on a
  48 px canvas, for the Arcticons icon pack (its rules: the drawing inside
  the 43 px template circle, round caps and joins, dots as 1.5 px squares).

    python3 dev/gen_mono_mark.py          # rewrite all four
    python3 dev/gen_mono_mark.py --check  # dev/verify.sh: stale = exit 1

Disc, star, hub, dot and pommels nest without touching (the star reaches
about 56.4 from the centre, the pommels start at 74), so even-odd knocks out
the star, the dot and the pommels and fills the hub again; the small
variant's star reaches about 61.3 and its hub starts inside the star's
notches (about 52.0 from the centre). The star is drawn
as one outline, the union of the two rounded squares: under even-odd, two
overlapping squares would turn their overlap back to filled.
"""
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DRAWABLE = ROOT / "app/src/main/res/drawable"

C = 100  # centre
POMMEL_R, POMMEL_RING = 6, 80
# The star's squares (half side, corner radius), the hub and the dot.
FULL = {"half": 44, "corner": 14, "hub": 30, "dot": 13}
SMALL = {"half": 48, "corner": 16, "hub": 34, "dot": 16}


def n(v):
    """Two decimals, no trailing zeros: the kit's own precision."""
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def circle(cx, cy, r):
    return f"M{n(cx - r)},{n(cy)}a{n(r)},{n(r)} 0 1,0 {n(2 * r)},0a{n(r)},{n(r)} 0 1,0 {n(-2 * r)},0Z"


def at(angle_deg, dist, c=C):
    a = math.radians(angle_deg)
    return c + dist * math.cos(a), c + dist * math.sin(a)


def star(half, corner, c=C):
    """The union of the squares at 0° and 45°: eight rounded points, each a
    corner of one square, joined through the eight points where an edge of
    one square crosses an edge of the other."""
    corner_centre = (half - corner) * math.sqrt(2)
    notch = half / math.cos(math.radians(22.5))
    d = []
    for k in range(8):
        tip = -90 + 45 * k  # this point's direction; screen y points down
        cx, cy = at(tip, corner_centre, c)
        a0, a1 = math.radians(tip - 45), math.radians(tip + 45)
        start = (cx + corner * math.cos(a0), cy + corner * math.sin(a0))
        end = (cx + corner * math.cos(a1), cy + corner * math.sin(a1))
        d.append(f"{'M' if k == 0 else 'L'}{n(start[0])},{n(start[1])}")
        d.append(f"A{n(corner)},{n(corner)} 0 0,1 {n(end[0])},{n(end[1])}")
        d.append("L{},{}".format(*map(n, at(tip + 22.5, notch, c))))
    return "".join(d) + "Z"


def path_data(small=False):
    g = SMALL if small else FULL
    pommels = "" if small else "".join(circle(*at(30 * i, POMMEL_RING), POMMEL_R) for i in range(12))
    return circle(C, C, 96) + pommels + star(g["half"], g["corner"]) + circle(C, C, g["hub"]) + circle(C, C, g["dot"])


HEADER_XML = """<?xml version="1.0" encoding="utf-8"?>
<!--
SPDX-FileCopyrightText: 2026 missing-foss

SPDX-License-Identifier: GPL-3.0-or-later
-->
<!-- Generated by dev/gen_mono_mark.py; edit that, not this. -->
"""


def vector(size_dp, fill, d):
    return HEADER_XML + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp" android:height="{size_dp}dp" android:viewportWidth="200" android:viewportHeight="200">
    <path android:fillColor="{fill}" android:fillType="evenOdd" android:pathData="{d}" />
</vector>
"""


def launcher_monochrome(d):
    return HEADER_XML + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="21" android:translateY="21" android:scaleX="0.3300" android:scaleY="0.3300">
        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{d}" />
    </group>
</vector>
"""


def svg(d):
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" width="200" height="200"><path fill="currentColor" fill-rule="evenodd" d="{d}"/></svg>
"""


ARCTICONS_HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
SPDX-FileCopyrightText: 2026 missing-foss

SPDX-License-Identifier: CC-BY-SA-4.0
-->
<!-- Generated by dev/gen_mono_mark.py; edit that, not this. -->
"""


def arcticons_svg():
    """The full mark as Arcticons draws icons: the disc's edge, the star, the
    hub and the dot as 1 px lines, the pommels as 1.5 px squares. The
    disc's 96 is scaled to the 43 px template circle's radius."""
    c, k = 24, 21.5 / 96
    g = FULL
    lines = [
        circle(c, c, 96 * k),
        star(g["half"] * k, g["corner"] * k, c),
        circle(c, c, g["hub"] * k),
        circle(c, c, g["dot"] * k),
    ]
    paths = "".join(
        f'  <path d="{d}" fill="none" stroke="#ffffff" stroke-width="1" '
        'stroke-linecap="round" stroke-linejoin="round"/>\n'
        for d in lines
    )
    dots = "".join(
        '  <rect x="{}" y="{}" width="1.5" height="1.5" fill="#ffffff"/>\n'.format(
            *(n(v - 0.75) for v in at(30 * i, POMMEL_RING * k, c))
        )
        for i in range(12)
    )
    return (
        ARCTICONS_HEADER
        + '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">\n'
        + paths
        + dots
        + "</svg>\n"
    )


def outputs():
    d = path_data()
    return {
        ROOT / "brand/trobar-mark-mono.svg": svg(d),
        DRAWABLE / "ic_trobar_mark_mono.xml": vector(48, "#FF000000", d),
        DRAWABLE / "ic_notification.xml": vector(48, "#FFFFFFFF", path_data(small=True)),
        DRAWABLE / "ic_launcher_monochrome.xml": launcher_monochrome(d),
        ROOT / "docs/icon-pack/arcticons.svg": arcticons_svg(),
    }


def main():
    stale = [p for p, text in outputs().items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        for p in stale:
            print(f"FAIL: {p.relative_to(ROOT)} is stale: run python3 dev/gen_mono_mark.py")
        if stale:
            sys.exit(1)
        print(f"ok ({len(outputs())} files, path of {len(path_data())} bytes)")
        return
    for p, text in outputs().items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(outputs())} files, path of {len(path_data())} bytes")


if __name__ == "__main__":
    main()
